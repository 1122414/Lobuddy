def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(ts_type(item) for item in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(item, ensure_ascii=False) for item in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        properties = schema.get("properties")
        if properties is None:
            additional = schema.get("additionalProperties", {})
            return f"Record<string, {ts_type(additional) if isinstance(additional, dict) else 'unknown'}>"
        required = schema.get("required", [])
        fields = [
            f"  {json.dumps(key)}{'' if key in required else '?'}: {ts_type(value)};"
            for key, value in properties.items()
        ]
        return "{\n" + "\n".join(fields) + "\n}"
    if kind in ("integer", "number"):
        return "number"
    if kind in ("string", "boolean", "null"):
        return str(kind)
    if not schema:
        return "unknown"
    raise ValueError(f"Unsupported schema construct: {schema.get('title', kind)}")


def generate() -> str:
    models: list[type[BaseModel]] = [
        JevStatus,
        ProjectOverview,
        ProjectView,
        SourceView,
        NotificationView,
        NotificationBatch,
        ScheduleView,
        DelegationDetail,
        DelegationView,
        DelegationRun,
        WorkflowView,
        Outcome,
        LearningView,
        RelationView,
        RpcRequest,
        ServiceEvent,
        TurnState,
        ChatSession,
        ChatMessage,
        PetState,
        ProgressOverview,
        SettingsView,
        ImageInfo,
        CompanionNotice,
        CompanionOverview,
        TopicView,
        ThemeView,
        MemoryItem,
        ConversationSummary,
        SessionSearchResponse,
        SkillRecord,
        SkillCandidate,
        SkillDetail,
        *METHODS.values(),
    ]
    definitions: dict[str, dict[str, Any]] = {}
    for model in models:
        schema = model.model_json_schema()
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    lines = ["// Generated by scripts/generate_desktop_protocol.py; do not edit manually.", ""]
    for name, schema in sorted(definitions.items()):
        lines.append(f"export type {name} = {ts_type(schema)};\n")
    lines.append("export interface ParametersByMethod {")
    lines.extend(f'  "{method}": {model.__name__};' for method, model in METHODS.items())
    lines.append("}\n")
    lines.append("export const METHOD_NAMES = " + json.dumps(list(METHODS)) + " as const;\n")
    lines.append(
        "export const TRANSIENT_METHOD_NAMES = "
        + json.dumps(sorted(TRANSIENT_METHODS))
        + " as const;\n"
    )
    return "\n".join(lines)


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / "shared/desktop-protocol.ts"
    target.parent.mkdir(exist_ok=True)
    target.write_text(generate(), encoding="utf-8")
