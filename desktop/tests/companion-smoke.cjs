// Native three-window acceptance, real stdio service, isolated durable data.
const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const { mkdtempSync, rmSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { execFileSync } = require('node:child_process');
const { resolve, join } = require('node:path');
(async () => {
  const temporary = mkdtempSync(join(tmpdir(), 'lobuddy-p6-ui-'));
  const env = { ...process.env, LOBUDDY_DATA_DIR: join(temporary, 'data'), LOBUDDY_WORKSPACE: join(temporary, 'workspace') };
  const source = join(temporary, 'pet.png');
  execFileSync(resolve(__dirname, '../../.venv/bin/python'), ['-c', 'from PIL import Image; import sys; Image.new("RGBA", (80,80), (220,60,80,255)).save(sys.argv[1])', source]);
  let application;
  const errors = [];
  try {
    application = await electron.launch({ args: [resolve(__dirname, '..')], env });
    const page = await application.firstWindow(); page.setDefaultTimeout(20000);
    page.on('pageerror', error => errors.push(error.message));
    await page.getByText('服务已连接', { exact: true }).waitFor().catch(async error => { console.log('Startup surface:', page.url(), (await page.locator('body').innerText()).slice(0, 500)); throw error; });
    await page.getByRole('button', { name: '外观', exact: true }).click();
    await page.getByRole('heading', { name: '让陪伴更像你喜欢的样子' }).waitFor();
    const pet = application.windows().find(item => item.url().includes('surface=pet'));
    assert.ok(pet); pet.on('pageerror', error => errors.push(error.message));
    await pet.getByRole('img', { name: '浊蒂' }).waitFor();
    const details = await application.evaluate(({ BrowserWindow }) => {
      const pet = BrowserWindow.getAllWindows().find(window => window.webContents.getURL().includes('surface=pet'));
      return { focusable: pet.isFocusable(), focused: pet.isFocused(), transparent: pet.getBackgroundColor(), bounds: pet.getBounds() };
    });
    assert.equal(details.focusable, false); assert.equal(details.focused, false);
    await pet.screenshot({ path: '/tmp/lobuddy-p6-pet.png', omitBackground: true });
    await page.getByLabel('宠物外观', { exact: true }).selectOption('skadi');
    await page.getByRole('button', { name: '保存外观', exact: true }).click();
    await page.getByText('外观已保存，桌宠会立即更新。', { exact: true }).waitFor();
    await pet.waitForFunction(() => getComputedStyle(document.querySelector('.pet-sprite')).backgroundImage.includes('skadi.webp'));
    await page.locator('.management-panel').evaluate(element => { element.scrollTop = 0; });
    await page.screenshot({ path: '/tmp/lobuddy-p6-appearance.png' });
    await page.getByRole('button', { name: '打开快速聊天', exact: true }).click();
    await page.waitForTimeout(500);
    const quick = application.windows().find(item => item.url().includes('surface=quick')); assert.ok(quick);
    quick.on('pageerror', error => errors.push(error.message));
    await quick.getByText('今天想聊什么？', { exact: true }).waitFor();
    await quick.screenshot({ path: '/tmp/lobuddy-p6-quick.png', omitBackground: true });
    await quick.getByLabel('消息', { exact: true }).fill('请简短地打个招呼。');
    await quick.getByRole('button', { name: '发送', exact: true }).click();
    await quick.waitForFunction(async () => (await window.lobuddy.request('task.list', {}, crypto.randomUUID())).some(task => task.status === 'completed'), null, { timeout: 150000 });
    await quick.getByRole('button', { name: '关闭快速聊天' }).click();
    await page.getByRole('button', { name: '对话', exact: true }).click();
    await page.locator('.message.user').getByText('请简短地打个招呼。', { exact: true }).waitFor();
    await page.getByRole('button', { name: '专注', exact: true }).click();
    await page.getByRole('button', { name: '开始专注', exact: true }).click();
    await page.getByText('专注中', { exact: true }).waitFor();
    await page.getByRole('button', { name: '暂停专注', exact: true }).click();
    await page.getByText('已暂停', { exact: true }).waitFor();
    await page.getByRole('button', { name: '继续专注', exact: true }).click();
    await page.getByText('专注中', { exact: true }).waitFor();
    await page.screenshot({ path: '/tmp/lobuddy-p6-focus.png' });
    await page.getByRole('button', { name: '结束专注', exact: true }).click();
    await page.getByText('准备好了就开始', { exact: true }).waitFor();
    await application.evaluate(({ BrowserWindow }) => {
      const pet = BrowserWindow.getAllWindows().find(window => window.webContents.getURL().includes('surface=pet'));
      pet.setPosition(70, 100);
    });
    await pet.evaluate(() => window.lobuddy.windowAction('drag-end'));
    const forbidden = await page.evaluate(async () => { try { await window.lobuddy.windowAction('drag-start'); return false; } catch { return true; } });
    assert.equal(forbidden, true);
    await page.getByRole('button', { name: '外观', exact: true }).click();
    await application.evaluate(({ dialog }, source) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [source] }); }, source);
    await page.getByRole('button', { name: '选择自定义图片', exact: true }).click();
    await pet.getByAltText('自定义伙伴').waitFor();
    await pet.waitForFunction(() => document.querySelector('.pet-custom').naturalWidth === 80);
    await page.getByRole('button', { name: '从图片提取配色', exact: true }).click();
    await page.getByText('图片配色已生成，保存外观后生效。', { exact: true }).waitFor();
    await page.getByRole('button', { name: '存为主题', exact: true }).click();
    await page.getByRole('button', { name: '应用', exact: true }).click();
    await page.getByLabel('宠物外观', { exact: true }).selectOption('skadi');
    await page.getByRole('button', { name: '保存外观', exact: true }).click();
    await page.getByText('外观已保存，桌宠会立即更新。', { exact: true }).waitFor();
    assert.deepEqual(errors, []);
    await application.close();
    application = await electron.launch({ args: [resolve(__dirname, '..')], env });
    const reopened = await application.firstWindow();
    await reopened.getByText('服务已连接', { exact: true }).waitFor();
    const config = await reopened.evaluate(() => window.lobuddy.request('companion.get', {}, crypto.randomUUID()));
    assert.equal(config.sprite, 'skadi');
    const bounds = await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(window => window.webContents.getURL().includes('surface=pet')).getBounds());
    assert.equal(bounds.x, 70); assert.equal(bounds.y, 100);
    console.log('PASS: actual nonfocusable transparent pet, appearance switch, quick chat with real model, shared session, focus lifecycle, IPC boundary, persisted position and preference');
  } finally { if (application) await application.close(); rmSync(temporary, { recursive: true, force: true }); }
})().catch(error => { console.error(error); process.exitCode = 1; });
