import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { MemoryItemSchema } from '@lobuddy/contracts';
import { Store } from './storage/database.js';
import { MemoryRepository } from './storage/memory.js';
import { MemoryWriteGateway } from './knowledge/gateway.js';
import { MemoryProjection } from './knowledge/projection.js';

test('gateway changes regenerate all six authoritative projections and deletion removes stale facts', async () => {
  const root = await mkdtemp(join(tmpdir(), 'lobuddy-projection-')), data = join(root, 'data'), workspace = join(root, 'workspace');
  await mkdir(workspace);
  const store = new Store(join(data, 'lobuddy.db'), { create: true });
  const repo = new MemoryRepository(store), projection = new MemoryProjection(data, workspace);
  const gateway = new MemoryWriteGateway(repo, () => projection.refresh(repo.list(undefined, undefined, undefined, 10000)));
  try {
    for (const [id, type, content, title, scope] of [
      ['user', 'user_profile', 'User likes tea', 'Basic Notes', 'global'],
      ['system', 'system_profile', 'Keep answers short', 'Style', 'global'],
      ['project', 'project_memory', 'Use TypeScript for Lobuddy', 'Architecture', 'lobuddy'],
    ]) gateway.saveAdmitted(MemoryItemSchema.parse({ id, memory_type: type, content, title, scope, source: 'ai_patch', confidence: 0.9 }));
    const paths = [join(data, 'memory/USER.md'), join(workspace, 'USER.md'), join(data, 'memory/SYSTEM.md'),
      join(workspace, 'SOUL.md'), join(data, 'memory/PROJECT.md'), join(workspace, 'memory/MEMORY.md')];
    const values = await Promise.all(paths.map(path => readFile(path, 'utf8')));
    for (const text of values) { assert.match(text, /^<!-- Generated by Lobuddy MemoryService/); assert.match(text, /SQLite memory_item is authoritative/); assert.match(text, /DO NOT EDIT/); }
    assert.match(values[0]!, /User likes tea/); assert.match(values[1]!, /Basic Information/);
    assert.match(values[2]!, /Keep answers short/); assert.match(values[3]!, /Personality/);
    assert.match(values[4]!, /lobuddy[\s\S]*Use TypeScript/);
    const body = (text: string) => text.slice(text.indexOf('-->') + 3);
    assert.equal(body(values[4]!), body(values[5]!));
    gateway.saveManual({ ...repo.get('project')!, content: 'Use SQLite for persistence' });
    for (const path of paths.slice(4)) { const text = await readFile(path, 'utf8'); assert.match(text, /SQLite for persistence/); assert.doesNotMatch(text, /TypeScript for Lobuddy/); }
    for (const id of ['user', 'system', 'project']) gateway.delete(id);
    for (const path of paths) assert.doesNotMatch(await readFile(path, 'utf8'), /User likes tea|Keep answers short|Use SQLite/);
    const first = gateway.identity('蒂蒂', 'session', 'source');
    const second = gateway.identity('蒂蒂', 'next-session', 'next-source');
    assert.equal(first.id, second.id); assert.equal(second.source_message_id, 'next-source');
    assert.equal(second.confidence, 0.95); assert.equal(second.source, 'strong_signal');
    gateway.identity('小蒂', 'next-session', 'last-source');
    assert.equal(repo.get(first.id)!.status, 'deprecated');
    assert.match(await readFile(join(workspace, 'SOUL.md'), 'utf8'), /小蒂/);
    assert.doesNotMatch(await readFile(join(workspace, 'SOUL.md'), 'utf8'), /蒂蒂/);
  } finally { store.close(); await rm(root, { recursive: true, force: true }); }
});
