import { createHash } from 'node:crypto';
import { lstatSync } from 'node:fs';
import { join } from 'node:path';
import { MemoryItemSchema, type MemoryItem } from '@lobuddy/contracts';
import { sanitizeMemory, stableIdentity } from '@lobuddy/domain';
import { WorkspaceFiles } from '../tools/files.js';
import type { MemoryWriteGateway } from './gateway.js';

class LegacyFiles extends WorkspaceFiles {
  override path(value: string): string {
    if (value !== 'memory/USER.md' && !/^memory\/USER\.[a-f0-9]{64}\.md\.bak$/.test(value)) throw Error('不是旧资料导入路径');
    return value;
  }
  exists(value: string): boolean {
    this.path(value);
    try { lstatSync(join(this.root,value)); return true; }
    catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') return false; throw error; }
  }
}

export function importLegacyProfile(data: string, gateway: MemoryWriteGateway): void {
  const repo = gateway.repository, store = repo.store, key = 'legacy-user-profile-import-v1';
  if (store.connection.prepare('SELECT 1 FROM knowledge_state WHERE name=?').get(key)) return;
  const files = new LegacyFiles(data, []), items: MemoryItem[] = [];
  let result = 'no-legacy-profile';
  if (repo.list('user_profile',undefined,undefined,1).length) result = 'existing-authoritative-profile';
  else if (files.exists('memory/USER.md')) {
    const bytes = files.readBytes('memory/USER.md',1024 * 1024);
    const text = new TextDecoder('utf-8',{ fatal: true }).decode(bytes);
    if (text.startsWith('<!-- Generated by Lobuddy MemoryService')) result = 'generated-projection-not-a-source';
    else {
      const hash = createHash('sha256').update(bytes).digest('hex'), backup = `memory/USER.${hash}.md.bak`;
      if (!files.exists(backup)) files.writeBytes(backup,bytes,true);
      if (!files.readBytes(backup,1024 * 1024).equals(bytes)) throw Error('旧资料备份校验失败');
      let title = 'Basic Notes';
      for (const [index,line] of text.split(/\r?\n/).entries()) {
        const heading = /^##\s+(.+?)\s*$/.exec(line);
        if (heading) { title = sanitizeMemory(heading[1]!); continue; }
        const bullet = /^- (.+)$/.exec(line.trim()), content = bullet && sanitizeMemory(bullet[1]!);
        if (content) items.push(MemoryItemSchema.parse({ id: stableIdentity(`legacy-user:${hash}:${index}`),
          memory_type: 'user_profile', title, content, source: 'migration', confidence: 0.9, importance: 0.7, priority: 70 }));
      }
      result = `imported:${hash}:${items.length}`;
    }
  }
  gateway.importLegacy(items, () => store.run('INSERT INTO knowledge_state VALUES(?,?)',key,result));
}

export function invalidIdentity(content: string): boolean {
  const normalized = content.trim().toLowerCase().replace(/[.。!！?？]+$/u,''), invalid = new Set(['who','what','unknown','谁','什么']);
  if (invalid.has(normalized)) return true;
  for (const prefix of ["the user's name is ",'my name is ']) if (normalized.startsWith(prefix)) {
    return invalid.has(normalized.slice(prefix.length).split('.')[0]!.trim());
  }
  return false;
}
