import { lstatSync } from 'node:fs';
import { join } from 'node:path';
import { localTimestamp, type MemoryItem } from '@lobuddy/contracts';
import { sanitizeMemory, unicodeCompare } from '@lobuddy/domain';
import { WorkspaceFiles } from '../tools/files.js';
const HEADER = '<!-- Generated by Lobuddy MemoryService';
class ProjectionFiles extends WorkspaceFiles {
  override path(value: string): string {
    if (!['memory','memory/USER.md','memory/SYSTEM.md','memory/PROJECT.md','memory/MEMORY.md','USER.md','SOUL.md'].includes(value)) {
      throw Error('不是受管记忆投影路径');
    }
    return value;
  }
  exists(path: string): boolean {
    this.path(path);
    try {
      const stat = lstatSync(join(this.root, path));
      if (!stat.isFile() || stat.nlink !== 1) throw Error('投影不能经过符号链接或特殊文件');
      return true;
    } catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') return false; throw error; }
  }
}
export class MemoryProjection {
  private readonly data: ProjectionFiles;
  private readonly workspace: ProjectionFiles;
  constructor(data: string, workspace: string) {
    this.data = new ProjectionFiles(data, []); this.workspace = new ProjectionFiles(workspace, []);
  }
  refresh(all: MemoryItem[]): void {
    const items = all.filter(item => item.status === 'active' && !(item.source === 'relationship' && item.scope !== 'global'));
    this.data.ensureDirectories('memory'); this.workspace.ensureDirectories('memory');
    const header = `${HEADER} at ${localTimestamp()}.\n     SQLite memory_item is authoritative. DO NOT EDIT this file directly.\n     Changes will be overwritten on next projection refresh. -->\n\n`;
    const write = (files: ProjectionFiles, path: string, values: MemoryItem[], render: (values: MemoryItem[]) => string) => {
      const exists = files.exists(path);
      if (values.length) files.atomicWrite(path, header + render(values));
      else if (exists && files.readBytes(path, 32 * 1024 * 1024).toString('utf8').startsWith(HEADER)) files.atomicWrite(path, header);
    };
    const grouped = (values: MemoryItem[], title: (item: MemoryItem) => string): string => {
      const groups = new Map<string, string[]>();
      for (const item of values) { const key = title(item); groups.set(key, [...(groups.get(key) ?? []), sanitizeMemory(item.content)]); }
      return [...groups.keys()].sort(unicodeCompare).map(key => `## ${sanitizeMemory(key)}\n\n${groups.get(key)!.map(text => `- ${text}`).join('\n')}\n`).join('\n');
    };
    const users = items.filter(v => v.memory_type === 'user_profile');
    write(this.data, 'memory/USER.md', users, values => grouped(values, item => item.title || 'Basic Notes'));
    write(this.workspace, 'USER.md', users, values => grouped(values, item => !item.title || item.title === 'Basic Notes' ? 'Basic Information' : item.title));
    const systems = items.filter(v => v.memory_type === 'system_profile');
    write(this.data, 'memory/SYSTEM.md', systems, values => `## System Behavior\n\n${values.map(v => `- ${sanitizeMemory(v.content)}`).join('\n')}\n`);
    write(this.workspace, 'SOUL.md', systems, values => `## Personality\n\n${values.map(v => `- ${sanitizeMemory(v.content)}`).join('\n')}\n`);
    const projects = items.filter(v => v.memory_type === 'project_memory');
    write(this.data, 'memory/PROJECT.md', projects, values => grouped(values, v => v.scope));
    write(this.workspace, 'memory/MEMORY.md', projects, values => grouped(values, v => v.scope));
  }
}
